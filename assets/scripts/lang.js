const kLS = "portfolio-lang";

function gTxt(k, l) {
    const src = dLng[l] || dLng.en;
    return src[k] !== undefined ? src[k] : dLng.en[k];
}

function aTxt(l) {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const k = el.getAttribute("data-i18n");
        const v = gTxt(k, l);
        if (k === "hero.line2") {
            el.innerHTML = v.replace("{name}", '<span class="bio__name">Aryngazy</span>');
        } else {
            el.textContent = v;
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        el.setAttribute("placeholder", gTxt(el.getAttribute("data-i18n-placeholder"), l));
    });

    document.documentElement.setAttribute("lang", l);

    const gEl = document.getElementById("about-greeting");
    const dEl = document.getElementById("about-description");
    if (gEl && gEl.dataset.typed === "1") gEl.textContent = gTxt("about.greet", l);
    if (dEl && dEl.dataset.typed === "1") dEl.textContent = gTxt("about.desc", l);
}

function mGl(wrap, btn) {
    if (!wrap || !btn) return;
    const gl = wrap.querySelector(".lang-switch__glider");
    if (!gl) return;
    const wR = wrap.getBoundingClientRect();
    const bR = btn.getBoundingClientRect();
    gl.style.width = bR.width + "px";
    gl.style.transform = `translateX(${bR.left - wR.left - 4}px)`;
}

function sBtns(l) {
    document.querySelectorAll(".lang-switch").forEach((wrap) => {
        let aBtn = null;
        wrap.querySelectorAll(".lang-switch__btn").forEach((b) => {
            const isA = b.getAttribute("data-lang") === l;
            b.classList.toggle("is-active", isA);
            if (isA) aBtn = b;
        });
        mGl(wrap, aBtn);
    });
}

function setLang(l) {
    if (!dLng[l]) l = "en";
    window.curLang = l;
    aTxt(l);
    sBtns(l);
    localStorage.setItem(kLS, l);
}

window.gLngTxt = gTxt;
window.setLang = setLang;

document.addEventListener("DOMContentLoaded", () => {
    const saved = localStorage.getItem(kLS);
    setLang(dLng[saved] ? saved : "en");

    document.querySelectorAll(".lang-switch__btn").forEach((b) => {
        b.addEventListener("click", () => setLang(b.getAttribute("data-lang")));
    });

    window.addEventListener("resize", () => sBtns(window.curLang || "en"));
});
